import os  # Standard library used to navigate computer folders and file paths
import re  # Standard library used for pattern matching text (Regular Expressions)
from datetime import datetime  # Standard library used to generate time-stamps for legal/audit tracking
from openpyxl import load_workbook  # Third-party library to read and modify raw Excel formulas

# REGEX PATTERN 1: Breaks the formula down into localized structural components.
# It splits text at symbols like + , - , * , / , ( , ) , commas, equals, or comparison characters.
FORMULA_SPLIT_RE = re.compile(r"([\+\-\*\/\(\),=\<\>])")

# REGEX PATTERN 2: Looks deeper into a specific formula segment for dangerous power traps.
# '\^' explicitly looks for the exponentiation caret symbol.
# '|' acts as an "OR" operator.
# 'POWER\s*\(' explicitly looks for Excel's native POWER function, ignoring spaces.
POWER_OP_RE = re.compile(r"(\^|POWER\s*\()", re.IGNORECASE)


def analyze_formula_tokens(formula_str):
    """Deeply inspects an Excel formula string to trace hidden nested unary negation risks.

    Returns:
        (bool, str): A boolean indicating if a risk exists, and the corrected
        formula string.
    """
    # Remove all whitespace to reliably track characters side-by-side
    clean_formula = "".join(formula_str.split())

    # Split the formula string into individual tokens while preserving the separator characters
    tokens = FORMULA_SPLIT_RE.split(clean_formula)
    # Remove empty string items generated by the splitting function
    tokens = [t for t in tokens if t != ""]

    has_risk = False
    patched_tokens = []

    # Loop through every separate piece of the formula sequentially
    for i, token in enumerate(tokens):
        # Identify if a minus sign is acting as a unary operator (negation instead of subtraction)
        if token == "-":
            is_unary = False

            # Case A: The minus is at the very beginning right after the equals sign (e.g., "=-4^2")
            if i == 1 and tokens[0] == "=":
                is_unary = True
            # Case B: The minus directly follows another operator or boundary bracket (e.g., "=A+(-B^2)")
            elif i > 0 and tokens[i - 1] in [
                "+",
                "-",
                "*",
                "/",
                "(",
                ",",
                "=",
                "<",
                ">",
            ]:
                is_unary = True

            if is_unary:
                # Look ahead to see what this specific minus sign is modifying before the next main boundary
                lookahead_idx = i + 1
                power_found_in_segment = False

                while lookahead_idx < len(tokens):
                    next_token = tokens[lookahead_idx]
                    # Stop inspecting if we hit a boundary that resets standard term binding
                    if next_token in ["+", "-", ")", ",", "=", "<", ">"]:
                        break
                    # If an exponent caret or POWER operator is seen in this segment, the trap is sprung!
                    if POWER_OP_RE.search(next_token):
                        power_found_in_segment = True
                        break
                    lookahead_idx += 1

                # If this unary minus conflicts with a power operator, flag it as a critical risk
                if power_found_in_segment:
                    has_risk = True
                    # Swap the tricky '-' with '0-' to safely force standard algebraic subtraction order
                    patched_tokens.append("0-")
                    continue

        # If the token is not a risky unary minus, retain the character exactly as it was found
        patched_tokens.append(token)

    return has_risk, "".join(patched_tokens)


def write_to_audit_log(log_path, records):
    """Generates an evidentiary, time-stamped text log tracking spreadsheet calculations for legal/liability protection."""
    # Capture the exact calendar date and clock time of the audit scan
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    try:
        # Open (or create) the log file in "append" mode so it safely adds records without overwriting past scans
        with open(log_path, "a", encoding="utf-8") as log_file:
            for file_path, sheet, cell, orig, patched in records:
                log_file.write(f"[{timestamp}] LIABILITY AUDIT RECORD\n")
                log_file.write(f"FILE PATH: {file_path}\n")
                log_file.write(f"WORKSHEET: {sheet} | CELL COORDINATE: {cell}\n")
                log_file.write(
                    f"EXCEL NATIVE (RISK):     {orig}\n"
                )  # Documents Excel's legacy operator precedence trap
                log_file.write(
                    f"MATHEMATICAL CORRECTION:  {patched}\n"
                )  # Documents the standard BEDMAS compliance path
                log_file.write("-" * 80 + "\n")
        print(f"\n[LOGGED] Evidentiary log updated at: {log_path}")
    except Exception as e:
        print(f"[ERROR] Failed to compile text log: {e}")


def scan_and_fix_spreadsheets(root_folder, include_subs=True, auto_fix=False):
    """Scans target paths for math risks, logging anomalies and patching formulas if requested."""
    print(
        f"\nExecuting Audit: {root_folder} (Subdirectories: {'ENABLED' if include_subs else 'DISABLED'})\n"
        + "=" * 70
    )

    matches_found = []

    # Improvement 1 Logic: Choose strategy based on user prompt.
    # 'os.walk' searches recursively down all levels; 'os.scandir' restricts operations solely to the main root level.
    if include_subs:
        file_generator = (
            (dp, f)
            for dp, _, filenames in os.walk(root_folder)
            for f in filenames
        )
    else:
        file_generator = (
            (root_folder, entry.name)
            for entry in os.scandir(root_folder)
            if entry.is_file()
        )

    # Loop through the files found by our structural path generator
    for dirpath, filename in file_generator:
        # Only inspect standard modern Excel files, skipping background system temporary logs (~$)
        if filename.endswith(".xlsx") and not filename.startswith("~$"):
            file_path = os.path.join(dirpath, filename)
            try:
                # Load the spreadsheet. 'data_only=False' forces python to read raw formula strings rather than cell results.
                wb = load_workbook(file_path, data_only=False)
                file_has_updates = False

                # Scan through every worksheet tab present inside the active file
                for sheet_name in wb.sheetnames:
                    ws = wb[sheet_name]
                    # Systematically scan every active row and cell column
                    for row in ws.iter_rows():
                        for cell in row:
                            # Only target active text strings that explicitly start with a formula assignment operator (=)
                            if (
                                cell.value
                                and isinstance(cell.value, str)
                                and cell.value.startswith("=")
                             ):
                                formula = cell.value
                                # Run the formula string through our token validation analyzer engine
                                is_risky, patched_formula = (
                                    analyze_formula_tokens(formula)
                                )

                                if is_risky:
                                    # Output an alert showing the exact layout coordinates of the hidden risk string
                                    print(
                                        f"[CRITICAL PRECEDENCE RISK] {filename} | {sheet_name} | Cell: {cell.coordinate}"
                                    )
                                    print(f"    Raw Excel String: {formula}")

                                    # Save data context details for our final analytics/audit compliance record
                                    matches_found.append(
                                        (
                                            file_path,
                                            sheet_name,
                                            cell.coordinate,
                                            formula,
                                            patched_formula,
                                        )
                                    )

                                    # If active corrections were authorized, modify the active spreadsheet token
                                    if auto_fix:
                                        cell.value = patched_formula
                                        file_has_updates = True

                # Save modifications back to disk only if updates were applied
                if auto_fix and file_has_updates:
                    wb.save(file_path)
                    print(f"[SAVED] Successfully patched formula updates to {filename}")

            except Exception as e:
                # Safely log access limitations (like password locks) without crashing the entire scan sequence
                print(f"[ERROR] Skipping file {filename} (Access error): {e}")

    print("=" * 70)
    print(f"Scan complete. Found {len(matches_found)} math precedence risks.")
    return matches_found


